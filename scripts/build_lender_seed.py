"""Generate supabase/seed_lenders.sql from data/lender-parameters.json.

Run after editing the JSON:  python3 scripts/build_lender_seed.py
The JSON (or the matching spreadsheet) is the source of truth for lender params.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "data/lender-parameters.json").read_text())

def q(v):
    if v is None or v == "":
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def status_of(raw):
    r = raw.lower()
    if r.startswith("live"):
        return "signed"
    if r.startswith("pending") or r.startswith("in setup"):
        return "negotiating"
    if r.startswith("not signed"):
        return "prospect"
    return "prospect"

# Lenders in the network with no parameters on file yet, plus passed/dropped/contacted.
# (name, status, submission_email, notes)
extra = [
    ("Fundomate", "signed", None, "Submit via portal; params not on file"),
    ("Velocity Capital Group", "signed", None, "Params not on file"),
    ("Liquidity Access", "signed", None, "Params not on file"),
    ("South End Capital / Stearns Bank", "signed", None, "Params not on file"),
    ("CFG Merchant Solutions", "signed", "SGould@cfgms.com", "Params not on file"),
    ("Smart Step Funding", "signed", None, "Total Deposits Advance only; no Credit Card Advance (processor-locked); params not on file"),
    ("Vox Funding", "signed", None, "Params not on file"),
    ("BusinessFunds.com", "signed", None, "Specialty / low-bar term outlet; params not on file"),
    ("Preferred Funding Group", "signed", None, "Affiliate; params not on file"),
    ("Columbia Bank", "signed", None, "Two-way referral (bank declines in, too-clean files out)"),
    ("Lexio Capital", "negotiating", None, "Asked for processing carve-out in s10"),
    ("Cashable", "dropped", None, "30-day clawback conflict"),
    ("1st Alliance Group", "passed", None, None),
    ("Splash Advance", "passed", None, None),
    ("Biz Capital Miami", "passed", None, None),
    ("Fenix Capital Funding", "passed", None, None),
    ("Libertas Funding", "passed", None, None),
    ("Vader", "contacted", None, "No reply yet"),
    ("ByzFunder", "contacted", None, "No reply yet"),
    ("Fox", "contacted", None, "No reply yet"),
    ("Bitty", "contacted", None, "No reply yet"),
]

emails = {
    "Pathway Funding": "subs@pathwayfunding.com",
    "Malka Advance": "Deals@malkaadvance.com",
    "Merchant Cash HQ": "Lisa@merchantcashhq.com",
    "LendCap": "submissions@lendcapsolutions.com",
}

rows = []
for l in data["lenders"]:
    rows.append("(" + ", ".join([
        q(l["lender"]), q(status_of(l["status"])) + "::lender_status", q(l["status"]),
        "array[" + q(l["product"]) + "]", q(l["paper"]), q(l["positions"]),
        q(l["min_tib_months"]), q(l["min_monthly_revenue"]), q(l["min_fico"]),
        q(l["negative_day_limit"]), q(l["deal_min"]), q(l["deal_max"]), q(l["max_term"]),
        q(l["states_excluded"]), q(l["restricted_industries"]), q(l["required_stips"]),
        q(emails.get(l["lender"])), q(l["notes"]),
        q(json.dumps(l)) + "::jsonb",
    ]) + ")")

out = ["-- GENERATED by scripts/build_lender_seed.py from data/lender-parameters.json. Do not hand-edit.",
       f"-- Source updated: {data.get('updated')}", ""]
out.append("""insert into lenders (workspace_id, name, status, status_detail, products, paper, positions,
  min_tib_months, min_monthly_rev, min_fico, negative_day_limit, deal_min, deal_max, max_term,
  states_excluded, restricted_industries, required_stips, submission_email, notes, params)
select w.id, v.name, v.status, v.status_detail, v.products, v.paper, v.positions,
  v.min_tib, v.min_rev, v.min_fico, v.neg, v.dmin, v.dmax, v.term,
  case when v.states is null then '{}'::text[] else array[v.states] end,
  v.restricted, v.stips, v.email, v.notes, v.params
from workspaces w, (values
  """ + ",\n  ".join(rows) + """
) as v(name, status, status_detail, products, paper, positions, min_tib, min_rev, min_fico, neg,
       dmin, dmax, term, states, restricted, stips, email, notes, params)
where w.slug = 'batch-capital'
on conflict (workspace_id, name) do update set
  status = excluded.status, status_detail = excluded.status_detail, products = excluded.products,
  paper = excluded.paper, positions = excluded.positions, min_tib_months = excluded.min_tib_months,
  min_monthly_rev = excluded.min_monthly_rev, min_fico = excluded.min_fico,
  negative_day_limit = excluded.negative_day_limit, deal_min = excluded.deal_min,
  deal_max = excluded.deal_max, max_term = excluded.max_term, states_excluded = excluded.states_excluded,
  restricted_industries = excluded.restricted_industries, required_stips = excluded.required_stips,
  submission_email = coalesce(excluded.submission_email, lenders.submission_email),
  notes = excluded.notes, params = excluded.params, updated_at = now();
""")

xrows = [f"({q(n)}, {q(s)}::lender_status, {q(e)}, {q(nt)})" for n, s, e, nt in extra]
out.append("""insert into lenders (workspace_id, name, status, submission_email, notes)
select w.id, v.name, v.status, v.email, v.notes from workspaces w, (values
  """ + ",\n  ".join(xrows) + """
) as v(name, status, email, notes)
where w.slug = 'batch-capital'
on conflict (workspace_id, name) do nothing;
""")

srows = []
for i, s in enumerate(data["segments"], 1):
    name = re.sub(r"^\d+\.\s*", "", s["Segment"])
    key = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    srows.append("(" + ", ".join([q(key), str(i), q(name), q(s["Who to look for"]),
        q(s["Hard filters (all must be true)"]), q(s["Best lenders"]),
        q(s["Public signals an AI agent can use"])]) + ")")
out.append("""insert into segments (workspace_id, key, position, name, who, hard_filters, best_lenders, public_signals)
select w.id, v.* from workspaces w, (values
  """ + ",\n  ".join(srows) + """
) as v(key, position, name, who, hard_filters, best_lenders, public_signals)
where w.slug = 'batch-capital'
on conflict (workspace_id, key) do update set
  name = excluded.name, who = excluded.who, hard_filters = excluded.hard_filters,
  best_lenders = excluded.best_lenders, public_signals = excluded.public_signals;
""")

(ROOT / "supabase/seed_lenders.sql").write_text("\n".join(out))
print(f"{len(rows)} lenders with params, {len(xrows)} others, {len(srows)} segments")
