// Bundles the Obsidian vault's markdown into the app at build time, so agents
// always run against the brain docs committed in the repo.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const vault = new URL("../../vault/", import.meta.url).pathname;
const out = new URL("../lib/brains.generated.ts", import.meta.url).pathname;
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".md")) files[relative(vault, p)] = readFileSync(p, "utf8");
  }
})(vault);
if (!files["batch-capital/00-Lead-Brain.md"]) throw new Error("Lead Brain not found in vault/");
writeFileSync(out, `// GENERATED by scripts/bundle-brains.mjs. Do not edit.\nexport const BRAINS: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`);
console.log(`bundled ${Object.keys(files).length} vault files`);
